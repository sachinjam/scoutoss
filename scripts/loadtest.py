#!/usr/bin/env python3
"""Scale test: load synthetic studies, then check the copilot is correct and fast at that size.

    make loadtest                 # 10,000 studies into project LOADTEST, then measure
    make loadtest STUDIES=50000
    make loadtest-clean           # remove the load-test documents again

Needs a running stack (`make up`). Data is index-only (no XNAT, no images), generated by
`scoutoss-indexer loadtest` inside the indexer container. Questions are asked as `scoutadmin`,
whose admin role sees every project, and each answer is compared with ground truth computed
straight from OpenSearch, so a truncated or wrong count fails the run. Prints one JSON line per
step; exits non-zero on the first wrong answer or on a question slower than --max-seconds.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from e2e import PORT, compose_exec, edge, opensearch, step, token

COPILOT = f"https://app.localhost:{PORT}/api/copilot/query"


def exact_patients(index: str, query: dict[str, Any]) -> int:
    """Exact distinct patients. (The ``cardinality`` aggregation is an estimate: at 13,000
    patients it was off by 3, which is not good enough for ground truth.)"""
    return len(members(index, query))


def total(index: str, query: dict[str, Any]) -> int:
    body = {"size": 0, "track_total_hits": True, "query": query}
    return int(opensearch(f"/{index}/_search", body)["hits"]["total"]["value"])


def members(index: str, query: dict[str, Any]) -> set[str]:
    """All distinct patient pseudonyms matching ``query`` (paged composite aggregation)."""
    out: set[str] = set()
    after: dict[str, Any] | None = None
    while True:
        comp: dict[str, Any] = {
            "size": 10000,
            "sources": [{"p": {"terms": {"field": "patient_pseudonym"}}}],
        }
        if after:
            comp["after"] = after
        body = {"size": 0, "query": query, "aggs": {"m": {"composite": comp}}}
        agg = opensearch(f"/{index}/_search", body)["aggregations"]["m"]
        out.update(b["key"]["p"] for b in agg["buckets"])
        after = agg.get("after_key")
        if not after or not agg["buckets"]:
            return out


def ask(client: Any, bearer: str, question: str, session: str) -> tuple[dict[str, Any], float]:
    started = time.monotonic()
    resp = client.post(
        COPILOT,
        json={"question": question, "session_id": session},
        headers={"Authorization": f"Bearer {bearer}"},
    )
    elapsed = time.monotonic() - started
    if resp.status_code != 200:
        step("copilot", False, question=question, status=resp.status_code, body=resp.text[:300])
    body: dict[str, Any] = resp.json()
    return body, elapsed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--studies", type=int, default=10_000)
    parser.add_argument("--project", default="LOADTEST")
    parser.add_argument("--skip-load", action="store_true", help="measure the data already there")
    parser.add_argument("--max-seconds", type=float, default=5.0, help="per-question budget")
    args = parser.parse_args()

    if not args.skip_load:
        out = compose_exec(
            "indexer",
            "scoutoss-indexer",
            "loadtest",
            "--studies",
            str(args.studies),
            "--project",
            args.project,
        )
        loaded = json.loads(out.strip().splitlines()[-1])
        step("load", loaded["failed"] == 0 and loaded["studies"] == args.studies, **loaded)

    everything = {"match_all": {}}
    ct = {"term": {"modalities": "CT"}}
    lung = {"term": {"diagnosis_category": "LUNG_CANCER"}}
    ct_chest_u85 = {
        "bool": {
            "filter": [
                ct,
                {"term": {"body_parts": "CHEST"}},
                {"range": {"patient_age": {"lt": 85}}},
            ]
        }
    }
    cross = members("dicom_studies", ct_chest_u85) & members("clinical_events", lung)
    female = {"term": {"patient_sex": "F"}}
    cross_female = cross & members("dicom_studies", female)
    step(
        "ground-truth",
        True,
        studies=total("dicom_studies", everything),
        patients=exact_patients("dicom_studies", everything),
        ct_studies=total("dicom_studies", ct),
    )

    client = edge()
    bearer = token(client, "scoutadmin")
    # (question, expected patients, expected studies or None)
    cases: list[tuple[str, int, int | None]] = [
        ("how many CT studies", exact_patients("dicom_studies", ct), total("dicom_studies", ct)),
        (
            "how many studies",
            exact_patients("dicom_studies", everything),
            total("dicom_studies", everything),
        ),
        ("patients under 85 with lung cancer AND CT chest", len(cross), None),
        ("of those, how many are female?", len(cross_female), None),
    ]
    slowest = 0.0
    for question, patients, studies in cases:
        times = []
        for _ in range(3):
            # a fresh session for the three stand-alone questions; the follow-up continues one
            answer, elapsed = ask(client, bearer, question, "loadtest")
            times.append(elapsed)
            if question.startswith("of those"):
                break
        got_p, got_s = answer.get("cohort_count"), answer.get("study_count")
        ok = got_p == patients and (studies is None or got_s == studies)
        ok = ok and not any(
            "truncat" in w.lower() or "first" in w.lower() for w in answer["warnings"]
        )
        slowest = max(slowest, statistics.median(times))
        step(
            "copilot",
            ok,
            question=question,
            patients=got_p,
            expected_patients=patients,
            studies=got_s,
            expected_studies=studies,
            seconds=round(statistics.median(times), 2),
            warnings=answer["warnings"],
        )
    step("speed", slowest <= args.max_seconds, slowest_seconds=round(slowest, 2))

    search = []
    for _ in range(20):
        started = time.monotonic()
        opensearch(
            "/dicom_studies/_search",
            {
                "size": 20,
                "query": ct_chest_u85,
                "aggs": {"by_year": {"terms": {"field": "study_year", "size": 20}}},
            },
        )
        search.append(time.monotonic() - started)
    step(
        "search",
        True,
        note="includes docker exec + curl overhead per call",
        median_ms=round(statistics.median(search) * 1000),
        p95_ms=round(sorted(search)[18] * 1000),
    )
    print("LOADTEST PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
