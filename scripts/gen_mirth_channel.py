#!/usr/bin/env python3
"""Generate the Mirth Connect channel export services/hl7-gateway/channel/scoutoss-hl7-ingest.xml.

The JavaScript lives in transformer.js (readable, diffable); this script embeds it into a
Mirth 4.5 channel definition:

  TCP Listener (MLLP, port 6661, HL7v2)
    -> source transformer: HL7 -> {"events": [...]} JSON + service token + traceparent
    -> HTTP Sender: POST ${INDEXER_URL}/clinical/events (Bearer token)
  ACK: auto-generated after the destination completes (AA on success, AE on failure)
  Storage: metadata only, content removed on completion (no PHI retained in Mirth).
"""

from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
CHANNEL_DIR = ROOT / "services" / "hl7-gateway" / "channel"
CHANNEL_ID = "5c0a7e1e-0b5d-4d5e-9c1a-5c0a7e1e0001"
V = "4.5.2"


def hl7_props(tag: str) -> str:
    p = "com.mirth.connect.plugins.datatypes.hl7v2"
    return f"""<{tag} class="{p}.HL7v2DataTypeProperties" version="{V}">
  <serializationProperties class="{p}.HL7v2SerializationProperties" version="{V}">
    <handleRepetitions>true</handleRepetitions>
    <handleSubcomponents>true</handleSubcomponents>
    <useStrictParser>false</useStrictParser>
    <useStrictValidation>false</useStrictValidation>
    <stripNamespaces>true</stripNamespaces>
    <segmentDelimiter>\\r</segmentDelimiter>
    <convertLineBreaks>true</convertLineBreaks>
  </serializationProperties>
  <deserializationProperties class="{p}.HL7v2DeserializationProperties" version="{V}">
    <useStrictParser>false</useStrictParser>
    <useStrictValidation>false</useStrictValidation>
    <segmentDelimiter>\\r</segmentDelimiter>
  </deserializationProperties>
  <batchProperties class="{p}.HL7v2BatchProperties" version="{V}">
    <splitType>MSH_Segment</splitType>
    <batchScript></batchScript>
  </batchProperties>
  <responseGenerationProperties class="{p}.HL7v2ResponseGenerationProperties" version="{V}">
    <segmentDelimiter>\\r</segmentDelimiter>
    <successfulACKCode>AA</successfulACKCode>
    <successfulACKMessage></successfulACKMessage>
    <errorACKCode>AE</errorACKCode>
    <errorACKMessage>An Error Occurred Processing Message.</errorACKMessage>
    <rejectedACKCode>AR</rejectedACKCode>
    <rejectedACKMessage>Message Rejected.</rejectedACKMessage>
    <msh15ACKAccept>false</msh15ACKAccept>
    <dateFormat>yyyyMMddHHmmss.SSS</dateFormat>
  </responseGenerationProperties>
  <responseValidationProperties class="{p}.HL7v2ResponseValidationProperties" version="{V}">
    <successfulACKCode>AA,CA</successfulACKCode>
    <errorACKCode>AE,CE</errorACKCode>
    <rejectedACKCode>AR,CR</rejectedACKCode>
    <validateMessageControlId>true</validateMessageControlId>
    <originalMessageControlId>Destination_Encoded</originalMessageControlId>
    <originalIdMapVariable></originalIdMapVariable>
  </responseValidationProperties>
</{tag}>"""


def raw_props(tag: str) -> str:
    p = "com.mirth.connect.plugins.datatypes.raw"
    return f"""<{tag} class="{p}.RawDataTypeProperties" version="{V}">
  <batchProperties class="{p}.RawBatchProperties" version="{V}">
    <splitType>JavaScript</splitType>
    <batchScript></batchScript>
  </batchProperties>
</{tag}>"""


def transformer(tag: str, steps: str, inbound: str, outbound: str) -> str:
    props = {"HL7V2": hl7_props, "RAW": raw_props}
    return f"""<{tag} version="{V}">
  <elements>{steps}</elements>
  <inboundTemplate encoding="base64"></inboundTemplate>
  <outboundTemplate encoding="base64"></outboundTemplate>
  <inboundDataType>{inbound}</inboundDataType>
  <outboundDataType>{outbound}</outboundDataType>
  {props[inbound]("inboundProperties")}
  {props[outbound]("outboundProperties")}
</{tag}>"""


RESOURCES = """<resourceIds class="linked-hash-map">
  <entry><string>Default Resource</string><string>[Default Resource]</string></entry>
</resourceIds>"""


def channel(script: str) -> str:
    step = f"""
    <com.mirth.connect.plugins.javascriptstep.JavaScriptStep version="{V}">
      <name>HL7 to ScoutOSS clinical event JSON</name>
      <sequenceNumber>0</sequenceNumber>
      <enabled>true</enabled>
      <script>{escape(script)}</script>
    </com.mirth.connect.plugins.javascriptstep.JavaScriptStep>"""
    return f"""<channel version="{V}">
  <id>{CHANNEL_ID}</id>
  <nextMetaDataId>2</nextMetaDataId>
  <name>ScoutOSS HL7 ingest</name>
  <description>MLLP (6661) HL7v2 ADT^A01/A08, ORM^O01, ORU^R01 -> ScoutOSS indexer /clinical/events. Generated by scripts/gen_mirth_channel.py; do not edit by hand.</description>
  <revision>1</revision>
  <sourceConnector version="{V}">
    <metaDataId>0</metaDataId>
    <name>sourceConnector</name>
    <properties class="com.mirth.connect.connectors.tcp.TcpReceiverProperties" version="{V}">
      <pluginProperties/>
      <listenerConnectorProperties version="{V}">
        <host>0.0.0.0</host>
        <port>6661</port>
      </listenerConnectorProperties>
      <sourceConnectorProperties version="{V}">
        <responseVariable>Auto-generate (Destinations completed)</responseVariable>
        <respondAfterProcessing>true</respondAfterProcessing>
        <processBatch>false</processBatch>
        <firstResponse>false</firstResponse>
        <processingThreads>1</processingThreads>
        {RESOURCES}
        <queueBufferSize>1000</queueBufferSize>
      </sourceConnectorProperties>
      <transmissionModeProperties class="com.mirth.connect.plugins.mllpmode.MLLPModeProperties">
        <pluginPointName>MLLP</pluginPointName>
        <startOfMessageBytes>0B</startOfMessageBytes>
        <endOfMessageBytes>1C0D</endOfMessageBytes>
        <useMLLPv2>false</useMLLPv2>
        <ackBytes>06</ackBytes>
        <nackBytes>15</nackBytes>
        <maxRetries>2</maxRetries>
      </transmissionModeProperties>
      <serverMode>true</serverMode>
      <remoteAddress></remoteAddress>
      <remotePort></remotePort>
      <overrideLocalBinding>false</overrideLocalBinding>
      <reconnectInterval>5000</reconnectInterval>
      <receiveTimeout>0</receiveTimeout>
      <bufferSize>65536</bufferSize>
      <maxConnections>10</maxConnections>
      <keepConnectionOpen>true</keepConnectionOpen>
      <dataTypeBinary>false</dataTypeBinary>
      <charsetEncoding>DEFAULT_ENCODING</charsetEncoding>
      <respondOnNewConnection>0</respondOnNewConnection>
      <responseAddress></responseAddress>
      <responsePort></responsePort>
    </properties>
    {transformer("transformer", step, "HL7V2", "HL7V2")}
    <filter version="{V}"><elements/></filter>
    <transportName>TCP Listener</transportName>
    <mode>SOURCE</mode>
    <enabled>true</enabled>
    <waitForPrevious>true</waitForPrevious>
  </sourceConnector>
  <destinationConnectors>
    <connector version="{V}">
      <metaDataId>1</metaDataId>
      <name>ScoutOSS indexer</name>
      <properties class="com.mirth.connect.connectors.http.HttpDispatcherProperties" version="{V}">
        <pluginProperties/>
        <destinationConnectorProperties version="{V}">
          <queueEnabled>false</queueEnabled>
          <sendFirst>false</sendFirst>
          <retryIntervalMillis>10000</retryIntervalMillis>
          <regenerateTemplate>false</regenerateTemplate>
          <retryCount>3</retryCount>
          <rotate>false</rotate>
          <includeFilterTransformer>false</includeFilterTransformer>
          <threadCount>1</threadCount>
          <threadAssignmentVariable></threadAssignmentVariable>
          <validateResponse>false</validateResponse>
          {RESOURCES}
          <queueBufferSize>1000</queueBufferSize>
          <reattachAttachments>true</reattachAttachments>
        </destinationConnectorProperties>
        <host>${{indexer_url}}</host>
        <useProxyServer>false</useProxyServer>
        <proxyAddress></proxyAddress>
        <proxyPort></proxyPort>
        <method>post</method>
        <headers class="linked-hash-map">
          <entry><string>Authorization</string><list><string>Bearer ${{token}}</string></list></entry>
          <entry><string>traceparent</string><list><string>${{traceparent}}</string></list></entry>
        </headers>
        <parameters class="linked-hash-map"/>
        <useHeadersVariable>false</useHeadersVariable>
        <headersVariable></headersVariable>
        <useParametersVariable>false</useParametersVariable>
        <parametersVariable></parametersVariable>
        <responseXmlBody>false</responseXmlBody>
        <responseParseMultipart>true</responseParseMultipart>
        <responseIncludeMetadata>false</responseIncludeMetadata>
        <responseBinaryMimeTypes>application/, image/, video/, audio/</responseBinaryMimeTypes>
        <responseBinaryMimeTypesRegex>false</responseBinaryMimeTypesRegex>
        <multipart>false</multipart>
        <useAuthentication>false</useAuthentication>
        <authenticationType>Basic</authenticationType>
        <usePreemptiveAuthentication>false</usePreemptiveAuthentication>
        <username></username>
        <password></password>
        <content>${{payload}}</content>
        <contentType>application/json</contentType>
        <dataTypeBinary>false</dataTypeBinary>
        <charset>UTF-8</charset>
        <socketTimeout>30000</socketTimeout>
      </properties>
      {transformer("transformer", "", "HL7V2", "HL7V2")}
      {transformer("responseTransformer", "", "RAW", "RAW")}
      <filter version="{V}"><elements/></filter>
      <transportName>HTTP Sender</transportName>
      <mode>DESTINATION</mode>
      <enabled>true</enabled>
      <waitForPrevious>true</waitForPrevious>
    </connector>
  </destinationConnectors>
  <preprocessingScript>return message;</preprocessingScript>
  <postprocessingScript>return;</postprocessingScript>
  <deployScript>return;</deployScript>
  <undeployScript>return;</undeployScript>
  <properties version="{V}">
    <clearGlobalChannelMap>true</clearGlobalChannelMap>
    <messageStorageMode>METADATA</messageStorageMode>
    <encryptData>true</encryptData>
    <encryptAttachments>true</encryptAttachments>
    <encryptCustomMetaData>true</encryptCustomMetaData>
    <removeContentOnCompletion>true</removeContentOnCompletion>
    <removeOnlyFilteredOnCompletion>false</removeOnlyFilteredOnCompletion>
    <removeAttachmentsOnCompletion>true</removeAttachmentsOnCompletion>
    <initialState>STARTED</initialState>
    <storeAttachments>false</storeAttachments>
    <metaDataColumns>
      <metaDataColumn>
        <name>MSGTYPE</name>
        <type>STRING</type>
        <mappingName>message_type</mappingName>
      </metaDataColumn>
    </metaDataColumns>
    <attachmentProperties version="{V}">
      <type>None</type>
      <properties/>
    </attachmentProperties>
    {RESOURCES}
  </properties>
  <exportData>
    <metadata>
      <enabled>true</enabled>
    </metadata>
    <dependentIds/>
    <dependencyIds/>
    <channelTags/>
  </exportData>
</channel>
"""


def main() -> None:
    script = (CHANNEL_DIR / "transformer.js").read_text()
    out = CHANNEL_DIR / "scoutoss-hl7-ingest.xml"
    out.write_text(channel(script))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
