"""The copilot pipeline: question -> prompt -> LLM -> validate -> execute -> charts ->
cohort -> answer. Numbers in the answer are computed, never generated by the model."""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from typing import Any

import structlog
from opentelemetry import trace
from prometheus_client import Counter

from scoutoss_common.phi import redact_text
from scoutoss_copilot.charts import choose_charts
from scoutoss_copilot.cohorts import CohortRepo, ConversationMemory, new_cohort
from scoutoss_copilot.executor import CohortResult, Executor
from scoutoss_copilot.llm import LLMProvider, Message, RedactingLLM
from scoutoss_copilot.plan import PlanValidationError, QueryPlan, validate_plan
from scoutoss_copilot.prompt import allow_terms, build_messages

log = structlog.get_logger(__name__)
tracer = trace.get_tracer(__name__)

QUERIES = Counter("copilot_queries_total", "Copilot questions answered", ["outcome"])

SEX_WORDS = {"F": "female", "M": "male", "O": "other", "U": "unknown"}


class CohortNotFound(LookupError):
    pass


@dataclass
class Answer:
    answer_text: str
    cohort_count: int
    study_count: int
    charts: list[dict[str, Any]]
    generated_query: dict[str, Any]
    executed_queries: list[dict[str, Any]]
    cohort_id: str | None
    studies: list[dict[str, Any]]
    stats: dict[str, Any]
    session_id: str
    question: str
    warnings: list[str]
    provider: str

    def to_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)


def _fmt_breakdown(
    counts: dict[str, int], labels: dict[str, str] | None = None, top: int = 4
) -> str:
    items = sorted(counts.items(), key=lambda kv: -kv[1])[:top]
    return ", ".join(f"{(labels or {}).get(k, k)} {v}" for k, v in items)


def compose_answer(plan: QueryPlan, result: CohortResult) -> str:
    s = result.stats
    if result.patient_count == 0:
        return "No patients match these criteria in the de-identified index."
    noun = "patient" if result.patient_count == 1 else "patients"
    study_noun = "study" if s["studies"] == 1 else "studies"
    if plan.subject == "studies":
        text = f"Found {s['studies']} {study_noun} from {result.patient_count} {noun}."
    else:
        text = f"Found {result.patient_count} {noun} ({s['studies']} imaging {study_noun})."
    parts = []
    if s.get("modality"):
        parts.append(f"Modalities: {_fmt_breakdown(s['modality'])}.")
    if s.get("sex"):
        parts.append(f"Sex: {_fmt_breakdown(s['sex'], SEX_WORDS)}.")
    if s.get("age_mean") is not None:
        parts.append(f"Mean age at study {s['age_mean']:.1f} years.")
    if s.get("diagnosis"):
        parts.append(f"Diagnoses: {_fmt_breakdown(s['diagnosis'])}.")
    if result.truncated:
        parts.append("Results were capped at 10,000 rows; counts may be incomplete.")
    return " ".join([text, *parts])


class Copilot:
    def __init__(
        self,
        *,
        llm: LLMProvider,
        executor: Executor,
        cohorts: CohortRepo,
        memory: ConversationMemory,
        schema: Any,
        max_rows: int = 10_000,
    ) -> None:
        self.schema = schema
        self.llm = RedactingLLM(llm, allow_terms=lambda: allow_terms(self.schema.get()))
        self.provider = llm.name
        self.executor = executor
        self.cohorts = cohorts
        self.memory = memory
        self.max_rows = max_rows

    def plan(self, question: str, user: str, session_id: str) -> tuple[QueryPlan, list[Message]]:
        schema = self.schema.get()
        history = self.memory.history(user, session_id)
        messages = build_messages(question, schema, history)
        with tracer.start_as_current_span("copilot.llm", attributes={"provider": self.provider}):
            raw = self.llm.complete(messages)
        return validate_plan(raw, max_rows=self.max_rows), messages

    def ask(
        self,
        question: str,
        *,
        user: str,
        session_id: str,
        projects: frozenset[str] | None = None,
    ) -> Answer:
        clean_question = redact_text(question)
        warnings: list[str] = []
        if clean_question != question:
            warnings.append("Identifiers were removed from your question before processing.")
        try:
            plan, _ = self.plan(clean_question, user, session_id)
        except PlanValidationError:
            QUERIES.labels("rejected").inc()
            raise
        base: set[str] | None = None
        if plan.base_cohort_id:
            prior = self.cohorts.get(plan.base_cohort_id, user)
            if prior is None:
                warnings.append(
                    "The referenced earlier cohort was not found; searched everything instead."
                )
                plan.base_cohort_id = None
            else:
                base = set(prior.members)
        with tracer.start_as_current_span("copilot.execute", attributes={"steps": len(plan.steps)}):
            result = self.executor.execute(plan, base_cohort=base, projects=projects)
        charts = choose_charts(plan.charts, result.stats)
        generated = plan.model_dump(exclude_none=True)
        cohort = self.cohorts.create(
            new_cohort(
                name=f"Cohort: {clean_question[:80]}",
                question=clean_question,
                query=generated,
                members=result.pseudonyms,
                study_uids=result.study_uids,
                user=user,
            )
        )
        self.memory.add(
            user,
            session_id,
            {"question": clean_question, "plan": generated, "cohort_id": cohort.id},
        )
        QUERIES.labels("ok" if result.patient_count else "empty").inc()
        log.info(
            "query answered",
            steps=len(plan.steps),
            patients=result.patient_count,
            studies=result.stats.get("studies", 0),
            provider=self.provider,
            question_hash=hashlib.sha256(clean_question.encode()).hexdigest()[:12],
        )
        if result.truncated:
            warnings.append("One or more steps matched more than 10,000 rows.")
        return Answer(
            answer_text=compose_answer(plan, result),
            cohort_count=result.patient_count,
            study_count=int(result.stats.get("studies", 0)),
            charts=charts,
            generated_query=generated,
            executed_queries=[
                s.executed | {"query": _shorten(s.executed["query"])} for s in result.steps
            ],
            cohort_id=cohort.id,
            studies=result.studies[:25],
            stats=result.stats,
            session_id=session_id,
            question=clean_question,
            warnings=warnings,
            provider=self.provider,
        )


def _shorten(query: dict[str, Any]) -> dict[str, Any]:
    """Executed queries may carry a long pseudonym list (follow-ups); show its size only."""
    text = str(query)
    if len(text) < 4000:
        return query
    return {"note": f"query with {text.count('SP')} cohort pseudonyms (elided)"}
